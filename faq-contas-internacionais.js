const topicButtons = Array.from(topicList.querySelectorAll(".faq-theme"));

function activateTopic(topicIndex, openQuestionId = null) {
  topicButtons.forEach((button, index) => {
    const active = index === topicIndex;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
    button.setAttribute("aria-current", String(active));
  });

  Array.from(faqContent.querySelectorAll(".faq-category")).forEach((category, index) => {
    category.hidden = index !== topicIndex;
  });

  if (openQuestionId) {
    const question = document.getElementById(openQuestionId);
    if (question instanceof HTMLDetailsElement) question.open = true;
  }
}

topicButtons.forEach((button, topicIndex) => {
  button.classList.toggle("is-active", topicIndex === 0);
  button.addEventListener("click", () => activateTopic(topicIndex));
});

function openQuestionFromHash() {
  const questionId = window.location.hash.slice(1);
  const question = document.getElementById(questionId);
  if (!(question instanceof HTMLDetailsElement)) return;

  const category = question.closest(".faq-category");
  if (!(category instanceof HTMLElement)) return;
  const topicIndex = Array.from(faqContent.querySelectorAll(".faq-category")).indexOf(category);
  if (topicIndex >= 0) activateTopic(topicIndex, questionId);
}

openQuestionFromHash();
window.addEventListener("hashchange", openQuestionFromHash);
